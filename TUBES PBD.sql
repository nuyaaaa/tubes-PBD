SET FOREIGN_KEY_CHECKS = 0;

CREATE DATABASE IF NOT EXISTS belajarKuy;
USE belajarKuy;

DROP TABLE IF EXISTS Nilai;
DROP TABLE IF EXISTS Sertifikat;
DROP TABLE IF EXISTS Langganan;
DROP TABLE IF EXISTS Review;
DROP TABLE IF EXISTS Konten;
DROP TABLE IF EXISTS Kategori;
DROP TABLE IF EXISTS Modul;
DROP TABLE IF EXISTS Promo;
DROP TABLE IF EXISTS Kursus;
DROP TABLE IF EXISTS Transaksi;
DROP TABLE IF EXISTS Siswa;
DROP TABLE IF EXISTS Instruktur;
DROP TABLE IF EXISTS Userq;

CREATE TABLE Userq (
  userId VARCHAR(5),
  nama VARCHAR(50),
  email VARCHAR(100),
  noTelepon VARCHAR(15),
  tipeUser VARCHAR(50),
  foto BLOB,
  tglDaftar DATETIME,
  PRIMARY KEY (userId)
);

CREATE TABLE Instruktur (
  instrukturId VARCHAR(5) NOT NULL,
  userId VARCHAR(5),
  statusVerifikasi VARCHAR(50),
  PRIMARY KEY (instrukturId),
  FOREIGN KEY (userId) REFERENCES Userq (userId)
);

CREATE TABLE Kategori (
  kategoriId VARCHAR(10) NOT NULL,
  namaKategori VARCHAR(50),
  PRIMARY KEY (kategoriId)
);

CREATE TABLE Kursus (
  kursusId VARCHAR(10) NOT NULL,
  judul VARCHAR(100),
  deskripsi TEXT,
  levelsulit INT,
  harga INT,
  ujian TEXT,
  instrukturId VARCHAR(5),
  kategoriId VARCHAR(10),
  PRIMARY KEY (kursusId),
  FOREIGN KEY (instrukturId) REFERENCES Instruktur (instrukturId),
  FOREIGN KEY (kategoriId) REFERENCES Kategori (kategoriId)
);

CREATE TABLE Promo (
  promoId VARCHAR(5) NOT NULL,
  kodePromo VARCHAR(50),
  potongan DECIMAL(10,2),
  masaBerlaku DATETIME,
  tipePromo VARCHAR(50),
  PRIMARY KEY (promoId)
);

CREATE TABLE Modul (
  modulId VARCHAR(5) NOT NULL,
  judulModul VARCHAR(100),
  materi TEXT,
  kuis TEXT,
  tugas TEXT,
  kursusId VARCHAR(10),
  PRIMARY KEY (modulId),
  FOREIGN KEY (kursusId) REFERENCES Kursus (kursusId)
);

CREATE TABLE Konten (
  kontenId VARCHAR(5) NOT NULL,
  modulId VARCHAR(5),
  tipeKonten VARCHAR(50),
  isiMateri TEXT,
  izinUnduh BOOLEAN,
  PRIMARY KEY (kontenId),
  FOREIGN KEY (modulId) REFERENCES Modul (modulId)
);

CREATE TABLE Review (
  reviewId VARCHAR(5) NOT NULL,
  userId VARCHAR(5),
  kursusId VARCHAR(5),
  rating INT,
  komentar TEXT,
  balasanInstruktur TEXT,
  PRIMARY KEY (reviewId),
  FOREIGN KEY (userId) REFERENCES Userq (userId),
  FOREIGN KEY (kursusId) REFERENCES Kursus (kursusId)
);

CREATE TABLE Langganan (
  langgananId VARCHAR(5) NOT NULL,
  userId VARCHAR(5),
  tipePaket VARCHAR(50),
  tanggalMulai DATETIME,
  tanggalBerakhir DATETIME,
  statusLangganan VARCHAR(50),
  PRIMARY KEY (langgananId),
  FOREIGN KEY (userId) REFERENCES Userq (userId)
);

CREATE TABLE Sertifikat (
  sertifikatId VARCHAR(5) NOT NULL,
  userId VARCHAR(5),
  kursusId VARCHAR(10),
  noSertifikat VARCHAR(50),
  tanggalTerbit DATETIME,
  PRIMARY KEY (sertifikatId),
  FOREIGN KEY (userId) REFERENCES Userq (userId),
  FOREIGN KEY (kursusId) REFERENCES Kursus (kursusId)
);

CREATE TABLE Nilai (
  nilaiId VARCHAR(5) NOT NULL,
  modulId VARCHAR(5),
  nilaiKuis INT,
  nilaiTugas INT,
  nilaiUjian INT,
  PRIMARY KEY (nilaiId),
  FOREIGN KEY (modulId) REFERENCES Modul (modulId)
);

CREATE TABLE Transaksi (
  transaksiId VARCHAR(5) NOT NULL,
  userId VARCHAR(5) NOT NULL,
  promoId VARCHAR(5) NOT NULL,
  kursusId VARCHAR(10) NOT NULL,
  metode VARCHAR(50),
  statusPembayaran BOOLEAN,
  tanggalTransaksi DATETIME,
  totalHarga INT,
  PRIMARY KEY (transaksiId),
  FOREIGN KEY (userId) REFERENCES Userq (userId),
  FOREIGN KEY (promoId) REFERENCES Promo (promoId),
  FOREIGN KEY (kursusId) REFERENCES Kursus (kursusId)
);

CREATE TABLE Siswa (
  siswaId VARCHAR(5) NOT NULL,
  tanggalBelajar DATETIME,
  userId VARCHAR(5),
  kursusId VARCHAR(10),
  PRIMARY KEY (siswaId),
  FOREIGN KEY (userId) REFERENCES Userq (userId),
  FOREIGN KEY (kursusId) REFERENCES Kursus (kursusId)
);


