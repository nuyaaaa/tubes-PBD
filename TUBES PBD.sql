-- QUERY SIMPEL
/* Soal 1: Tampilkan semua data dari tabel Kursus dan kursus mana yang paling banyak diambil oleh siswa */
SELECT * 
FROM kursus;

SELECT 
	K.kursusId,
	K.judul,
	COUNT(Siswa.kursusId) AS jumlahSiswa
FROM kursus K
JOIN Siswa ON K.kursusId = Siswa.kursusId
ORDER BY jumlahSiswa DESC;


/* Soal 2: Tampilkan data promo yang bertipe Diskon lalu hitung rata rata diskon */
SELECT promoId, kodePromo, potongan, tipePromo
FROM Promo
WHERE tipePromo = 'Diskon';

SELECT AVG(potongan) AS rataRataDiskon
FROM Promo
WHERE tipePromo = 'Diskon';


-- QUERY COMPLEX
/* Soal 3: Hitung rata-rata nilai ujian dari seluruh modul,
lalu tampilkan nama modul yang mendapatkan nilai tertinggi diantara modul lainnya */
SELECT AVG(nilaiUjian) AS rataRataNilaiUjian
FROM Nilai;

SELECT m.judulModul, n.nilaiUjian
FROM Nilai n
JOIN Modul m ON n.modulId = m.modulId
ORDER BY n.nilaiUjian DESC
LIMIT 1;

/* Soal 4: Tampilkan kursus yang memiliki harga di atas rata-rata harga semua kursus,
lalu tampilkan user yang membeli kursus tersebut */
SELECT k.kursusId, k.judul, k.harga, u.userId, u.nama
FROM Kursus k
JOIN Transaksi t ON k.kursusId = t.kursusId
JOIN Userq u ON t.userId = u.userId
WHERE k.harga > (SELECT AVG(harga) FROM Kursus);


-- QUERY MULTITABLE
/* Soal 5: Tampilkan userId, nama user, promo yang digunakan, 
dan harga kursus untuk transaksi dengan harga kursus di bawah rata-rata harga kursus */
SELECT u.userId, u.nama, p.kodePromo, k.harga
FROM Transaksi t
JOIN Userq u ON t.userId = u.userId
JOIN Promo p ON t.promoId = p.promoId
JOIN Kursus k ON t.kursusId = k.kursusId
WHERE k.harga < (SELECT AVG(harga) FROM Kursus);

/* Soal 6: Tampilkan instruktur, judul kursus, rating, dan komentar dari review yang diberikan oleh siswa */
SELECT i.instrukturId, u.nama AS namaInstruktur, k.judul, r.rating, r.komentar
FROM Review r
JOIN Kursus k ON r.kursusId = k.kursusId
JOIN Instruktur i ON k.instrukturId = i.instrukturId
JOIN Userq u ON i.userId = u.userId;
